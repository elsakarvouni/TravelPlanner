#!/usr/bin/env node

/**
 * Dev-time codegen: builds the static world map SVG paths and a slim
 * country list, so the app never ships d3-geo/topojson-client/world-countries
 * (with all their translations data) at runtime.
 *
 * Run manually with: node scripts/generate-world-map-data.js
 * Re-run only if the country/map data needs to be regenerated.
 */

const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const d3geo = require('d3-geo');
const worldCountries = require('world-countries');
const topology = require('world-atlas/countries-50m.json');

const VIEW_BOX_WIDTH = 960;
const VIEW_BOX_HEIGHT = 500;

const geo = topojson.feature(topology, topology.objects.countries);

// Antarctica isn't relevant for a travel tracker and eats vertical space.
geo.features = geo.features.filter((feature) => feature.id !== '010');

const projection = d3geo.geoNaturalEarth1().fitSize([VIEW_BOX_WIDTH, VIEW_BOX_HEIGHT], geo);
const pathGenerator = d3geo.geoPath(projection).digits(0);

const numericToCca2 = new Map(worldCountries.map((country) => [country.ccn3, country.cca2]));

const pathsByCode = new Map();
const unmatched = [];

for (const feature of geo.features) {
  const cca2 = numericToCca2.get(feature.id);
  const d = pathGenerator(feature);
  if (!cca2 || !d) {
    unmatched.push(feature.properties?.name ?? feature.id);
    continue;
  }
  // A country can be split across multiple features (e.g. Australia +
  // its outlying islands share the same ISO code) — merge into one path.
  const existing = pathsByCode.get(cca2);
  pathsByCode.set(cca2, existing ? `${existing} ${d}` : d);
}

if (unmatched.length > 0) {
  console.warn(`Skipped ${unmatched.length} unmatched map features:`, unmatched.join(', '));
}

const paths = Array.from(pathsByCode.entries()).map(([code, d]) => ({ code, d }));

const mapOutput = `// AUTO-GENERATED by scripts/generate-world-map-data.js — do not edit by hand.

export const WORLD_MAP_VIEW_BOX = '0 0 ${VIEW_BOX_WIDTH} ${VIEW_BOX_HEIGHT}';

export const WORLD_MAP_PATHS: { code: string; d: string }[] = ${JSON.stringify(paths)};
`;

const assetsDir = path.join(__dirname, '..', 'assets', 'data');
fs.mkdirSync(assetsDir, { recursive: true });
fs.writeFileSync(path.join(assetsDir, 'world-map.ts'), mapOutput);

const unMemberCountries = worldCountries
  .filter((country) => country.unMember)
  .map((country) => ({
    code: country.cca2,
    name: country.name.common,
    region: country.region,
    flag: country.flag,
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const countriesOutput = `// AUTO-GENERATED by scripts/generate-world-map-data.js — do not edit by hand.

export type CountryInfo = {
  code: string;
  name: string;
  region: string;
  flag: string;
};

export const UN_COUNTRIES: CountryInfo[] = ${JSON.stringify(unMemberCountries, null, 2)};
`;

fs.writeFileSync(path.join(assetsDir, 'countries.ts'), countriesOutput);

console.log(`Wrote ${paths.length} country map paths and ${unMemberCountries.length} UN countries.`);
