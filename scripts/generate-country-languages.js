const fs = require('fs');
const path = require('path');
const countries = require('world-countries');

// Overrides for countries where the first language key in world-countries
// isn't the language most useful for a visiting tourist.
const PRIMARY_LANGUAGE_OVERRIDES = {
  NO: 'nob', // Bokmål, not Nynorsk
  IL: 'heb',
  CH: 'deu', // German is the majority language, not French
  BE: 'nld', // Dutch/Flemish is the majority language, not German
  AT: 'deu', // world-countries only lists Austro-Bavarian for Austria
  CA: 'eng',
  KE: 'eng',
  IN: 'eng',
  PK: 'eng',
  PH: 'eng',
  SG: 'eng',
  MT: 'eng',
  ZA: 'eng',
  AR: 'spa', // world-countries lists Guaraní before Spanish
  BY: 'rus',
  BZ: 'eng',
  BO: 'spa',
  CM: 'fra',
  CW: 'nld',
  GQ: 'spa',
  GU: 'eng',
  KZ: 'rus',
  KG: 'rus',
  LU: 'fra',
  MO: 'zho',
  MP: 'eng',
  NA: 'eng',
  PE: 'spa',
  PY: 'spa', // world-countries lists Guaraní before Spanish
  SC: 'eng',
  TD: 'fra',
  VU: 'eng',
  ZW: 'eng',
};

const result = {};

for (const country of countries) {
  const langs = country.languages;
  if (!langs) continue;
  const keys = Object.keys(langs);
  if (keys.length === 0) continue;
  result[country.cca2] = PRIMARY_LANGUAGE_OVERRIDES[country.cca2] ?? keys[0];
}

const outPath = path.join(__dirname, '..', 'assets', 'data', 'country-languages.ts');
const content = `// Auto-generated by scripts/generate-country-languages.js — do not edit by hand.
export const COUNTRY_LANGUAGES: Record<string, string> = ${JSON.stringify(result, null, 2)};
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log('Wrote', outPath, 'with', Object.keys(result).length, 'countries');
